/**
 * PolicyTranslator.js
 * Translates DOG ownership edges into Rego policy rules that can be
 * loaded by RuleKeeper Manager's PolicyManager and compiled to WASM.
 *
 * Key integration point between K9db's DOG abstraction and RuleKeeper's
 * OPA-based policy enforcement.
 *
 * Output Rego rules are appended to:
 *   rulekeeper/RuleKeeper Manager/policies/access_control.rego
 */

const { inferOwners } = require('./OwnershipInference');

class PolicyTranslator {
  /**
   * @param {import('./Graph').Graph} dog
   */
  constructor(dog) {
    this.dog = dog;
  }

  /**
   * Generate Rego allow rules for access_control.rego.
   * A principal can access a collection if they are an inferred owner.
   *
   * @returns {string} Rego source to append to access_control.rego
   */
  generateAccessControlRego() {
    const lines = [
      '# ===== DOG-derived access control rules (auto-generated) =====',
      '# Generated by src/dog/PolicyTranslator.js — do not edit manually.',
      '',
    ];

    for (const collection of this.dog.getCollections()) {
      const owners = inferOwners(this.dog, collection);
      if (owners.length === 0) continue;

      lines.push(`# Collection: ${collection}`);
      for (const owner of owners) {
        const pathComment = owner.path.join(' -> ');
        lines.push(`# Ownership path: ${pathComment} (${owner.type})`);
        lines.push(`dog_allow_${collection.toLowerCase()}[userId] {`);
        lines.push(`  # Principal userId is the ${owner.dataSubject} owner via ${owner.path[1]}`);
        lines.push(`  doc := data.${collection.toLowerCase()}[_]`);
        lines.push(`  userId := doc.${owner.path[1]}`);
        lines.push(`}`);
        lines.push('');
      }

      // Umbrella allow rule (injected into RuleKeeper's allow evaluation)
      lines.push(`allow {`);
      lines.push(`  input.operation.collection == "${collection}"`);
      lines.push(`  dog_allow_${collection.toLowerCase()}[input.principal]`);
      lines.push(`}`);
      lines.push('');
    }

    return lines.join('\n');
  }

  /**
   * Generate SAR (Subject Access Request) policies from the DOG.
   * Maps OWNED_BY + onDelete=CASCADE → delete, ANONYMIZE → nullify.
   *
   * Returns a JSON object consumable by our SAR handler.
   * @returns {Object} sarPolicies
   */
  generateSARPolicies() {
    const policies = {};

    for (const collection of this.dog.getCollections()) {
      const edges = this.dog.getEdgesFrom(collection);
      policies[collection] = {
        onForget: [],
        onAccess: [],
      };

      for (const edge of edges) {
        if (edge.type === 'OWNED_BY') {
          if (edge.onDelete === 'CASCADE') {
            policies[collection].onForget.push({ action: 'delete', field: edge.field, subject: edge.to });
          } else if (edge.onDelete === 'ANONYMIZE') {
            policies[collection].onForget.push({ action: 'nullify', field: edge.field, subject: edge.to });
          }
          // For SAR access: include this collection when subject requests their data
          policies[collection].onAccess.push({ field: edge.field, subject: edge.to });
        }
      }
    }

    return policies;
  }
}

module.exports = { PolicyTranslator };
